"""End-to-end pipeline validation on synthetic data with known parameters.

Generates eva-shaped synthetic extracts, runs the REAL config (modeling/
config.yaml, with only the data paths swapped) through the hibayes CLI, and
checks the posteriors recover the generating parameters:

    uv run python -m modeling.synth.run_synth

Anything that breaks here -- config typos, processor bugs, model
misspecification -- breaks before real data is ever involved.
"""

import subprocess
import sys
from pathlib import Path

import yaml

from modeling.synth import check_recovery, make_synthetic

REPO = Path(__file__).resolve().parent.parent.parent
BASE_CONFIG = REPO / "modeling" / "config.yaml"
SYNTH_CONFIG = REPO / "modeling" / "synth" / ".config.yaml"
SYNTH_OUT = REPO / "modeling" / "synth" / ".output"


def write_synth_config() -> None:
    """The real config with only the data paths pointed at data/synth/."""
    config = yaml.safe_load(BASE_CONFIG.read_text())
    config["data_loader"]["paths"]["extracted_data"] = [
        f"data/synth/{b}.samples.parquet" for b in make_synthetic.BENCHMARKS
    ]
    SYNTH_CONFIG.write_text(
        "# GENERATED by modeling/synth/run_synth.py -- edit modeling/config.yaml instead\n"
        + yaml.safe_dump(config, sort_keys=False)
    )


def main() -> int:
    make_synthetic.generate(seed=0)
    write_synth_config()

    cmd = [
        "uv", "run", "hibayes-full",
        "--config", str(SYNTH_CONFIG),
        "--out", str(SYNTH_OUT),
        "--no-tui",
    ]
    print("[synth] running:", " ".join(cmd))
    result = subprocess.run(cmd, cwd=REPO)
    if result.returncode != 0:
        print("[synth] hibayes-full failed")
        return result.returncode

    return check_recovery.main()


if __name__ == "__main__":
    sys.exit(main())
